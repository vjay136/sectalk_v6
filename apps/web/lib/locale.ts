const catalogs = { en, ar }
const compiled = new Map<string, IntlMessageFormat>()

export type PlainMessageKey = Exclude<MessageKey, 'keyboardShortcutCount'>
export type Message = [key: PlainMessageKey] |
  [key: 'keyboardShortcutCount', values: { count: number }]

export function formatMessage(locale: Locale, ...[key, values]: Message): string {
  const cacheKey = `${locale}:${key}`
  let message = compiled.get(cacheKey)
  if (!message) {
    message = new IntlMessageFormat(catalogs[locale][key], locales[locale].formattingLocale)
    compiled.set(cacheKey, message)
  }
  return String(message.format(values))
}
